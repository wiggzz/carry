//! Admission for the mandatory PENDING -> terminal representation. The physical
//! promise protects writes; this reservation independently protects the loadable
//! record's representation, including another outstanding lane on the same owner.
use super::*;
use serde::Serialize;

/// JSON's longest primitive is a signed 128-bit integer (40 bytes). Strings and
/// container punctuation keep their exact encoded size. Callers supply the full
/// possible shape, including optional receipt fields, not an arbitrary margin.
pub(crate) fn size_bound(value: &impl Serialize) -> std::io::Result<u64> {
    fn count(value: &Value) -> u64 {
        match value {
            Value::Array(values) => {
                2 + values.iter().map(count).sum::<u64>() + values.len().saturating_sub(1) as u64
            }
            Value::Object(values) => {
                2 + values
                    .iter()
                    .map(|(key, value)| {
                        serde_json::to_string(key).unwrap().len() as u64 + 1 + count(value)
                    })
                    .sum::<u64>()
                    + values.len().saturating_sub(1) as u64
            }
            Value::String(text) => serde_json::to_string(text).unwrap().len() as u64,
            _ => 40,
        }
    }
    Ok(count(&serde_json::to_value(value)?))
}

pub(super) fn reserve(
    service: &Service,
    session: &mut Session,
    body: &Value,
    primary: bool,
) -> std::io::Result<()> {
    let model = body["model"].as_str().unwrap_or("");
    let mut ledger = if primary {
        session.primary.clone()
    } else {
        session.shadow.clone()
    };
    // An unpriced completion may add exactly the dispatched model, never a
    // model supplied by an upstream response.
    ledger.unpriced_models.insert(model.into());
    let dispatch = if primary {
        &session.last_primary_dispatch
    } else {
        &session.last_reviewer_dispatch
    };
    let mut dispatch = dispatch.clone().ok_or_else(|| {
        std::io::Error::other("settlement admission requires its dispatch measurement")
    })?;
    dispatch.receipt_input_tokens = Some(0);
    dispatch.receipt_output_tokens = Some(0);
    dispatch.outcome = "completed".into();
    if !primary {
        // The transport's reviewer attempt ID replaces the scheduling ID.
        // Both are generated by the same bounded owner.
        dispatch.parent_request_id = Some(dispatch.request_id.clone());
        dispatch.basis = "receipt_first_or_local_visible_text_not_encoded_native_payloads".into();
        // logging::request_id is pid:u32 / epoch-nanos:u128 / sequence:u64.
        dispatch.request_id = format!("{}-{}-{}", u32::MAX, u128::MAX, u64::MAX);
    }
    let fields = json!({
        "ledger":ledger,
        "dispatch":dispatch,
        "completed_requests":0,
        "failed_primaries":0,
        "primary_pending":false,
        "background_review_pending":false,
        "last_failure":{
            "at":0,
            "request_id":if primary { session.last_primary_dispatch.as_ref().map_or("", |d| d.request_id.as_str()) } else { "" },
            "reason":"upstream stream ended before completion",
            "http_status":0,
            "complete_transport":false
        }
    });
    let evidence = session.request_evidence.as_ref().map_or(Ok(0), |e| {
        e.completion_bound(
            body,
            &service.config.upstream_url,
            service
                .config
                .model_resolution
                .as_ref()
                .map(|r| if primary { &r.primary } else { &r.reviewer }),
            primary,
        )
    })?;
    // Include the complete changed field envelope, rather than assuming any
    // existing numeric digit widths or missing optional fields remain fixed.
    let bytes = size_bound(&fields)?.checked_add(evidence).ok_or_else(|| {
        std::io::Error::new(
            std::io::ErrorKind::StorageFull,
            "settlement representation overflow",
        )
    })?;
    if primary {
        session.primary_settlement_bytes = Some(bytes);
    } else {
        session.reviewer_settlement_bytes = Some(bytes);
    }
    Ok(())
}

pub(super) fn outstanding(session: &Session) -> u64 {
    session
        .primary_settlement_bytes
        .filter(|_| session.primary_pending)
        .unwrap_or(0)
        .saturating_add(
            session
                .reviewer_settlement_bytes
                .filter(|_| session.background_review_pending)
                .unwrap_or(0),
        )
}
